const iconUrlCache = new Map()
const requiredItemsByQuestObj = new WeakMap()
const requiredItemsByQuestId = new Map()
const rewardsByQuestObj = new WeakMap()
const rewardsByQuestId = new Map()

export function resolveItemIconUrl(nameRaw) {
  if (!nameRaw) return assetUrl('game-maps/icons/T_UI_Icon_Task_Collect.png')
  if (typeof nameRaw === 'object') {
    const objTarget = nameRaw.icon || nameRaw.enName || nameRaw.name || nameRaw.zhName || nameRaw.item || ''
    return resolveItemIconUrl(objTarget)
  }
  const rawKey = String(nameRaw)
  const cached = iconUrlCache.get(rawKey)
  if (cached) return cached

  let clean = rawKey.replace(/^\d+[×x]\s*/i, '').trim()

  // Direct relative path check
  if (clean.startsWith('/weapons/') || clean.startsWith('/mods/') || clean.startsWith('/items/') || clean.startsWith('/outpost/')) {
    const url = assetUrl(clean)
    iconUrlCache.set(rawKey, url)
    return url
  }

  // Extract parenthetical English if format is "中文名 (English Name)"
  const parenMatch = clean.match(/\(([A-Za-z0-9\s'.\-&"]+)\)$/)
  const candidates = [clean]
  if (parenMatch) {
    candidates.unshift(parenMatch[1].trim())
    candidates.push(clean.replace(/\s*\([^)]+\)$/, '').trim())
  }
  if (ZH_TO_EN_MAP[clean]) {
    candidates.unshift(ZH_TO_EN_MAP[clean])
  }

  for (const cand of candidates) {
    if (!cand) continue
    // Blueprint check (note: "Project Heartwood Blueprints" is a quest item, not a recipe blueprint)
    if ((/\bBlueprint$/i.test(cand) || /蓝图$/.test(cand)) && !/Heartwood/i.test(cand) && !/常青计划/.test(cand)) {
      const url = assetUrl('items/T_UI_Icon_Recipe.png')
      iconUrlCache.set(rawKey, url)
      return url
    }

    // 1. Check weapon
    const wepSlug = cand
      .replace(/\s+(I|II|III|IV)$/i, '')
      .replace(/\s+/g, '_')
      .toLowerCase()
    if (WEAPON_SLUGS.has(wepSlug)) {
      const url = assetUrl(`weapons/${wepSlug}.png`)
      iconUrlCache.set(rawKey, url)
      return url
    }

    // 2. Check weapon mod
    const modSlug = cand.replace(/\s+/g, '-').toLowerCase()
    if (MOD_SLUGS.has(modSlug)) {
      const url = assetUrl(`mods/${modSlug}.png`)
      iconUrlCache.set(rawKey, url)
      return url
    }
    if (cand === 'Extended Barrel') {
      const url = assetUrl('mods/extended-barrel-iii.png')
      iconUrlCache.set(rawKey, url)
      return url
    }

    // 3. Check item icon map
    const normCand = cand.replace(/[“”]/g, '"').replace(/[‘’]/g, "'")
    const mappedEn = ZH_TO_EN_MAP[cand] || ZH_TO_EN_MAP[normCand] || normCand
    const itemPng = ITEM_ICON_MAP[mappedEn] || ITEM_ICON_MAP[cand] || ITEM_ICON_MAP[normCand]
    if (itemPng) {
      const url = assetUrl(`items/${itemPng}`)
      iconUrlCache.set(rawKey, url)
      return url
    }
  }

  const fallback = assetUrl('game-maps/icons/T_UI_Icon_Task_Collect.png')
  iconUrlCache.set(rawKey, fallback)
  return fallback
}

function parseEntry(enRaw, zhRaw) {
  const enStr = String(enRaw || '').trim()
  const zhStr = String(zhRaw || enRaw || '').trim()
  const countMatch = zhStr.match(/^(\d+)×\s*(.+)$/) || enStr.match(/^(\d+)×\s*(.+)$/)
  const count = countMatch ? `×${countMatch[1]}` : ''
  const cleanZh = zhStr.replace(/^\d+×\s*/, '').trim()
  const cleanEn = enStr.replace(/^\d+×\s*/, '').trim()
  const shortZh = cleanZh.replace(/\s*\([A-Za-z\s']+\)/g, '').trim()

  return Object.freeze({
    count,
    enName: cleanEn,
    zhName: shortZh || cleanZh,
    fullLabel: zhStr,
    icon: resolveItemIconUrl(cleanEn || shortZh),
  })
}

const EMPTY_FROZEN_ARRAY = Object.freeze([])

export function parseQuestRequiredItems(quest) {
  if (
    !quest ||
    !quest.zhRequiredItems ||
    quest.zhRequiredItems === '无须携带特定任务物品' ||
    quest.requiredItems === 'None'
  ) {
    return EMPTY_FROZEN_ARRAY
  }
  const byObj = requiredItemsByQuestObj.get(quest)
  if (byObj) return byObj
  if (quest.id && requiredItemsByQuestId.has(quest.id)) {
    const cached = requiredItemsByQuestId.get(quest.id)
    requiredItemsByQuestObj.set(quest, cached)
    return cached
  }

  const enParts = String(quest.requiredItems || '').split(/\s*•\s*/)
  const zhParts = String(quest.zhRequiredItems || '').split(/\s*·\s*/)
  const len = Math.max(enParts.length, zhParts.length)
  const out = []
  for (let i = 0; i < len; i++) {
    const en = enParts[i] || zhParts[i] || ''
    const zh = zhParts[i] || enParts[i] || ''
    if (!en && !zh) continue
    out.push(parseEntry(en, zh))
  }
  const frozen = Object.freeze(out)
  requiredItemsByQuestObj.set(quest, frozen)
  if (quest.id) requiredItemsByQuestId.set(quest.id, frozen)
  return frozen
}

export function parseQuestRewards(quest) {
  if (!quest || !Array.isArray(quest.zhRewards) || !quest.zhRewards.length) {
    return EMPTY_FROZEN_ARRAY
  }
  const byObj = rewardsByQuestObj.get(quest)
  if (byObj) return byObj
  if (quest.id && rewardsByQuestId.has(quest.id)) {
    const cached = rewardsByQuestId.get(quest.id)
    rewardsByQuestObj.set(quest, cached)
    return cached
  }

  const enList = Array.isArray(quest.rewards) ? quest.rewards : []
  const zhList = quest.zhRewards
  const frozen = Object.freeze(zhList.map((zh, i) => parseEntry(enList[i] || zh, zh)))
  rewardsByQuestObj.set(quest, frozen)
  if (quest.id) rewardsByQuestId.set(quest.id, frozen)
  return frozen
}
